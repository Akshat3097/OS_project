"""
Build a folder of sources to upload to NotebookLM, plus the prompt that makes it write training data in the format
qlora/import_notebooklm.py reads.

    python -m qlora.notebooklm_pack                      → ..\\notebooklm_sources (next to the project folder)

Upload every file in the folder as a source (NotebookLM takes PDF, Markdown and text), and paste the YouTube links
from youtube_links.txt as YouTube sources. Then paste GENERATION_PROMPT.md into the chat, once per topic.

Only explanations and conceptual questions come from NotebookLM. Worked numerical problems stay generated by the OS
Engine (build_chat_dataset.py), because a language model's arithmetic can't be trusted.
"""
from __future__ import annotations

import argparse
import json
import shutil
from pathlib import Path

import config
from tutor import faq
from tutor.lessons import LESSONS

ROOT = config.ROOT
TOPICS = ["scheduling basics", "FCFS", "SJF", "SRTF", "Round Robin", "priority scheduling", "critical section",
          "semaphores", "producer–consumer (bounded buffer)", "readers–writers", "dining philosophers", "deadlocks",
          "Banker's algorithm"]

PROMPT = """You are writing training data for OS Tutor, a tutor for the VIT BCSE303 Operating Systems course.
Use ONLY the uploaded sources. Follow these course conventions exactly (they are in "notes_conventions_checked.md"):
ties go to the earlier arrival, then list order; a LOWER priority number means HIGHER priority unless a question
says otherwise; in Round Robin a process that arrives exactly when a slice ends joins the queue BEFORE the preempted
process; TAT = CT − AT, WT = TAT − BT, RT = first start − AT; an unsafe state is NOT the same as deadlock.

Topic: {TOPIC}

Write 25 examples of a student message and the tutor's reply, about this topic only. Mix these kinds:
- a real student question: definitions, "why", "what if", comparisons, common confusions, exam-style theory
  questions (short and long), and vague ones like "why does this matter?" or "I don't get it";
- messages written the way students really type: short, informal, lowercase, small typos, Hinglish sometimes.

Each reply must:
- answer the question that was asked (not recite the whole topic), in 60 to 180 words;
- for "explain" questions: an everyday example from a college student's life in India first, then the exact rule;
- be correct by the sources; if the sources don't say, say so briefly instead of guessing;
- contain NO new numerical example (no made-up arrival or burst times, no Gantt charts, no matrices): numbers only
  when they are definitions or appear in the sources;
- speak to the student as "you", in Markdown, and end with one short question that checks understanding.

Output ONLY JSON Lines, one object per line, no other text, no code fences:
{"topic": "{TOPIC}", "user": "<student message>", "assistant": "<tutor reply>"}
"""


def lesson_markdown() -> str:
    out = ["# OS Tutor lessons (written and checked for this course)\n"]
    for l in LESSONS:
        out += [f"## {l['title']}", f"Goal: {l['goal']}", "", f"Everyday example: {l['analogy']}", "",
                l["concept"].strip(), "", "Another way to explain it:", l["alt"].strip(), "",
                "Key points: " + "; ".join(l["summary"]), ""]
        if l.get("real_life"):
            out += ["Real life:"] + [f"- {r}" for r in l["real_life"]] + [""]
        if l.get("ideas"):
            out += ["Key ideas a student must explain:"] + [f"- {i['statement']}" for i in l["ideas"]] + [""]
        if l.get("misconceptions"):
            out += ["Common misconceptions (these are WRONG):"] + [f"- {m['text']}" for m in l["misconceptions"]] + [""]
        for q in (l.get("mcq") or []):
            right = next(o for o in q["options"] if o[1])
            out += [f"Quiz: {q['q']}", f"Answer: {right[0]}. {right[2]}", ""]
    return "\n".join(out)


def faq_markdown() -> str:
    out = ["# Checked answers to tricky questions (BCSE303)\n"]
    for e in faq.ENTRIES:
        out += [f"## {e[1] or 'other'}", e[2], ""]
    return "\n".join(out)


def main() -> None:
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--out", type=Path, default=ROOT.parent / "notebooklm_sources")
    a = ap.parse_args()
    out = a.out
    out.mkdir(parents=True, exist_ok=True)
    n = 0
    for folder in (ROOT / "rag" / "sources", ROOT / "rag" / "knowledge"):
        for f in sorted(folder.iterdir()):
            if f.suffix.lower() in (".md", ".pdf", ".txt"):
                shutil.copy2(f, out / f.name)
                n += 1
    (out / "os_tutor_lessons.md").write_text(lesson_markdown(), encoding="utf-8")
    (out / "os_tutor_checked_answers.md").write_text(faq_markdown(), encoding="utf-8")
    videos = json.loads((ROOT / "videos" / "videos.json").read_text(encoding="utf-8"))
    (out / "youtube_links.txt").write_text("\n".join(v["url"] for v in videos) + "\n", encoding="utf-8")
    (out / "GENERATION_PROMPT.md").write_text(
        "# Paste this into NotebookLM once per topic (replace {TOPIC})\n\nTopics: " + ", ".join(TOPICS) +
        "\n\n---\n\n" + PROMPT, encoding="utf-8")
    print(f"{n + 2} source files, {len(videos)} YouTube links and the prompt in {out}")


if __name__ == "__main__":
    main()
