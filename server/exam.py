"""
Exam mode: a timed mock CAT paper generated by the OS Engine, marked automatically, that updates mastery.

  Q1 CPU scheduling (10)   Gantt chart 3, CT/TAT/WT table 6 (a value that follows correctly from an earlier slip gets
                           half marks, like method marks), average WT 1
  Q2 Banker's (6)          Need matrix 2, safe or unsafe 1, a valid safe sequence 3 (any valid order)
  Q3 Semaphores (4)        final values 2 (either convention), blocked processes 2
  Q4 Deadlock detection (5) deadlocked or not 2, which processes 3
  Q5 Concepts (5)          five multiple-choice questions from the lessons, 1 each

The paper and its answers stay on the server; the page gets the questions only, and the marking after it submits.
"""
from __future__ import annotations

import random
import threading
import time
import uuid

from engine import deadlock, generator, scheduling, semaphore
from server.cards import table
from tutor import chat_parse as cp
from tutor import lessons as L
