from tutor.student_model import SKILLS, StudentModel

MINUTES = 30
ALGOS = ["SJF", "SRTF", "RR", "PRIORITY_NP", "PRIORITY_P"]


class ExamError(ValueError):
    pass


def _detection_problem(rng: random.Random) -> dict:
    """A small detection question: about half the papers have a deadlock, and the rest need a few steps."""
    want_deadlock = rng.random() < 0.5
    for _ in range(5000):
        n, m = 4, 3
        alloc = [[rng.randint(0, 2) for _ in range(m)] for _ in range(n)]
        req = [[rng.randint(0, 2) for _ in range(m)] for _ in range(n)]
        avail = [rng.randint(0, 1) for _ in range(m)]
        if any(not any(r) for r in alloc):
            continue
        d = deadlock.detect(avail, alloc, req)
        if d["deadlock"] == want_deadlock and (len(d["sequence"]) >= (1 if want_deadlock else 4)):
            return {"available": avail, "allocation": alloc, "request": req}
    return {"available": [1, 0, 1], "allocation": [[0, 1, 0], [2, 0, 0], [1, 0, 1], [0, 1, 1]],
            "request": [[1, 0, 1], [0, 1, 1], [0, 0, 0], [2, 0, 0]]}


def _mcqs(rng: random.Random, k: int = 5) -> list[dict]:
    lessons = rng.sample(L.LESSONS, k)
    out = []
    for lesson in lessons:
        q = rng.choice(lesson["mcq"])
        opts = list(q["options"])
        rng.shuffle(opts)
        out.append({"lesson": lesson["title"], "q": q["q"], "options": [{"text": t, "ok": ok, "why": why} for t, ok, why in opts]})
    return out


def _vec(v) -> str:
    return " ".join(map(str, v))


# ============================================================================ the paper
def make_paper(seed: int | None = None) -> dict:
    rng = random.Random(seed)
    sched = generator.generate_scheduling(rng.choice(ALGOS), 2, rng.randrange(10**9))
    bank = generator.generate_bankers(2, rng.randrange(10**9))
    sem = generator.generate_semaphore(2, rng.randrange(10**9))
    return {"scheduling": sched.to_dict(), "bankers": bank.to_dict(), "semaphore": sem.to_dict(),
            "detection": _detection_problem(rng), "mcq": _mcqs(rng)}


def public_view(exam: dict) -> dict:
    """The paper as the student sees it: no answers."""
    p = exam["paper"]
    s = generator.problem_from_dict(p["scheduling"])
    pri = s.algorithm in scheduling.USES_PRIORITY
    b = generator.problem_from_dict(p["bankers"])
    m = generator.problem_from_dict(p["semaphore"])
    d = p["detection"]
    bp = [f"P{i}" for i in range(len(b.maximum))]
    dp = [f"P{i}" for i in range(len(d["allocation"]))]
    res = list("ABCDE")
    return {
        "id": exam["id"], "minutes": MINUTES, "started": exam["started"], "now": time.time(), "submitted": bool(exam.get("result")),
        "questions": [
            {"n": 1, "kind": "scheduling", "marks": 10, "title": scheduling.ALGORITHMS[s.algorithm] + (f", q = {s.quantum}" if s.quantum else ""),
             "text": "Draw the Gantt chart, then find the completion, turnaround and waiting time of every process and the average waiting time.",
             "table": table(["Process", "Arrival", "Burst"] + (["Priority"] if pri else []),
                            [[x.pid, x.arrival, x.burst] + ([x.priority] if pri else []) for x in s.processes]),
             "note": "Ties go to the earlier arrival." + (" Lower number = higher priority." if pri else "")
                     + (" A process arriving when a slice ends joins the queue before the preempted one." if s.algorithm == "RR" else ""),
             "pids": [x.pid for x in s.processes]},
            {"n": 2, "kind": "bankers", "marks": 6, "title": "Banker's algorithm",
             "text": "Find the Need matrix. Is the system in a safe state? If it is, give a safe sequence.",
             "tables": [{"label": "Allocation", **table(["", *b.resources], [[x, *r] for x, r in zip(bp, b.allocation)])},
                        {"label": "Max", **table(["", *b.resources], [[x, *r] for x, r in zip(bp, b.maximum)])}],
             "available": _vec(b.available), "resources": b.resources, "pids": bp},
            {"n": 3, "kind": "semaphore", "marks": 4, "title": "Semaphores",
             "text": "The operations run in this order. Give the final value of each semaphore and the processes still blocked "
                     "at the end. Either definition of wait/signal is accepted.",
             "initial": [[k, v] for k, v in m.initial.items()], "ops": [semaphore.format_op(o) for o in m.ops],
             "sems": list(m.initial), "pids": sorted({o["pid"] for o in m.ops})},
            {"n": 4, "kind": "detection", "marks": 5, "title": "Deadlock detection",
             "text": "Use the deadlock-detection algorithm. Is the system deadlocked? If so, which processes?",
             "tables": [{"label": "Allocation", **table(["", *res[:3]], [[x, *r] for x, r in zip(dp, d["allocation"])])},
                        {"label": "Request", **table(["", *res[:3]], [[x, *r] for x, r in zip(dp, d["request"])])}],
             "available": _vec(d["available"]), "pids": dp},
            {"n": 5, "kind": "mcq", "marks": 5, "title": "Concepts",
             "items": [{"lesson": q["lesson"], "q": q["q"], "options": [o["text"] for o in q["options"]]} for q in p["mcq"]]},
        ]}


# ============================================================================ marking
def _int(v):
    try:
        return int(str(v).strip())
    except (TypeError, ValueError):
        return None


def _num(v):
    try:
        return float(str(v).strip())
    except (TypeError, ValueError):
        return None


def mark_scheduling(pd: dict, ans: dict) -> tuple[dict, dict]:
    prob = generator.problem_from_dict(pd)
    res = prob.solve()
    pids = [x.pid for x in prob.processes]
    gantt = cp.parse_gantt_text(ans.get("gantt") or "", pids)
    metrics = {pid: {k: _int((ans.get("metrics") or {}).get(pid, {}).get(k)) for k in ("CT", "TAT", "WT")} for pid in pids}
    a = analyse_scheduling(prob, gantt or None, metrics)
    g = 3 if gantt and a.get("gantt_correct") else 0
    cells = [c for row in (a.get("cells") or {}).values() for c in row.values()]
    t = round(6 * sum(1 if c == "correct" else 0.5 if c == "consistent" else 0 for c in cells) / max(1, len(cells)), 1)
    avg = _num(ans.get("avg_wt"))
    w = 1 if avg is not None and abs(avg - res.avg_wt) < 0.011 else 0
    mistakes = [e["label"] for e in a.get("errors", []) if e.get("type") != "missing_value"]
    fb = {"marks": round(g + t + w, 1), "parts": [["Gantt chart", g, 3], ["CT / TAT / WT table", t, 6], ["Average WT", w, 1]],
          "mistakes": mistakes,
          "answer": {"gantt": " | ".join(f"{s.pid if s.pid != 'IDLE' else 'idle'} {s.start}–{s.end}" for s in res.gantt),
                     "table": table(["Process", "CT", "TAT", "WT"], [[r.pid, r.completion, r.turnaround, r.waiting] for r in res.results.values()]),
                     "avg_wt": f"{res.avg_wt:.2f}"}}
    return fb, a


def mark_bankers(pd: dict, ans: dict) -> tuple[dict, dict]:
    prob = generator.problem_from_dict(pd)
    need = ans.get("need")
    safe = ans.get("safe")
    seq = [x.strip().upper() for x in str(ans.get("sequence") or "").replace("→", ",").replace("<", "").replace(">", "")
           .replace(" ", ",").split(",") if x.strip()]
    a = analyse_bankers(prob, need, safe if isinstance(safe, bool) else None, seq or None)
    eng = a["engine"]
    cells = [c for row in (a.get("need_cells") or []) for c in row]
    n_marks = round(2 * sum(c == "correct" for c in cells) / max(1, len(cells)), 1) if cells else 0
    v_marks = 1 if isinstance(safe, bool) and safe == eng["safe"] else 0
    if eng["safe"]:
        s_marks = 3 if a.get("sequence_check") and a["sequence_check"]["valid"] else 0
    else:
        s_marks = 3 if safe is False else 0
    fb = {"marks": round(n_marks + v_marks + s_marks, 1),
          "parts": [["Need matrix", n_marks, 2], ["Safe or unsafe", v_marks, 1], ["Safe sequence" if eng["safe"] else "Spotting that no sequence exists", s_marks, 3]],
          "mistakes": [e["label"] for e in a.get("errors", []) if e.get("type") != "missing_value"],
          "answer": {"need": table(["", *prob.resources], [[f"P{i}", *r] for i, r in enumerate(eng["need"])]),
                     "verdict": ("Safe, e.g. " + " → ".join(eng["sequence"]) + " (any valid order earns the marks)") if eng["safe"]
                     else f"Unsafe: {', '.join(eng['stuck'])} can never finish"}}
    return fb, a


def mark_semaphore(pd: dict, ans: dict) -> tuple[dict, dict]:
    prob = generator.problem_from_dict(pd)
    final = {k: _int(v) for k, v in (ans.get("final") or {}).items()}
    blocked = [str(x).strip().upper() for x in (ans.get("blocked") or [])]
    a = analyse_semaphore(prob, final, blocked)
    tr = semaphore.trace(prob.initial, prob.ops)
    busy = {k: max(0, v) for k, v in tr["final_values"].items()}
    v_ok = all(final.get(k) in (v, busy[k]) for k, v in tr["final_values"].items())
    answered = any(v is not None for v in final.values())          # "nobody blocked" only counts on an attempted answer
    b_ok = answered and sorted(set(blocked)) == sorted(tr["blocked"])
    fb = {"marks": (2 if v_ok else 0) + (2 if b_ok else 0),
          "parts": [["Final values", 2 if v_ok else 0, 2], ["Blocked processes", 2 if b_ok else 0, 2]],
          "mistakes": [e["label"] for e in a.get("errors", []) if e.get("type") != "missing_value"],
          "answer": {"final": ", ".join(f"{k} = {v}" + (f" (or {busy[k]} with busy waiting)" if busy[k] != v else "")
                                         for k, v in tr["final_values"].items()),
                     "blocked": ", ".join(tr["blocked"]) or "none"}}
    return fb, a


def mark_detection(d: dict, ans: dict) -> dict:
    det = deadlock.detect(d["available"], d["allocation"], d["request"])
    said = ans.get("deadlock")
    who = sorted({str(x).strip().upper() for x in (ans.get("deadlocked") or [])})
    v = 2 if isinstance(said, bool) and said == det["deadlock"] else 0
    w = 3 if (det["deadlock"] and who == det["deadlocked"]) or (not det["deadlock"] and said is False) else 0
    return {"marks": v + w, "parts": [["Deadlocked or not", v, 2], ["Which processes" if det["deadlock"] else "No process deadlocked", w, 3]],
            "mistakes": [],
            "answer": {"verdict": (f"Deadlocked: {', '.join(det['deadlocked'])}" + (f" (only {', '.join(det['sequence'])} can finish)" if det["sequence"] else ""))
                       if det["deadlock"] else "No deadlock: every process can finish, e.g. " + " → ".join(det["sequence"]),
                       "steps": [f"{s['process']}: Request {_vec(s['request'])} ≤ Work {_vec(s['work_before'])} → Work = {_vec(s['work_after'])}"
                                 for s in det["steps"]]}}


def mark_mcq(items: list[dict], ans: list) -> dict:
    out, marks = [], 0
    for k, q in enumerate(items):
        choice = ans[k] if k < len(ans) else None
        picked = next((o for o in q["options"] if o["text"] == choice), None)
        right = next(o for o in q["options"] if o["ok"])
        ok = bool(picked and picked["ok"])
        marks += ok
        out.append({"q": q["q"], "ok": ok, "chosen": choice, "correct": right["text"], "why": (picked or right)["why"]})
    return {"marks": marks, "parts": [["Multiple choice", marks, len(items)]], "mistakes": [], "items": out}


# ============================================================================ exams in progress
class Exams:
    def __init__(self):
        self._data: dict[str, dict] = {}
        self._lock = threading.Lock()

    def start(self, sid: str, seed: int | None = None) -> dict:
        exam = {"id": uuid.uuid4().hex[:12], "sid": sid, "started": time.time(), "paper": make_paper(seed), "result": None}
        with self._lock:
            self._data[exam["id"]] = exam
        return public_view(exam)

    def get(self, exam_id: str) -> dict:
        exam = self._data.get(exam_id)
        if not exam:
            raise ExamError("That paper has expired (the server was restarted). Start a new one.")
        return exam

    def submit(self, exam_id: str, answers: dict, students: StudentModel) -> dict:
        with self._lock:
            exam = self.get(exam_id)
            if exam["result"]:
                return exam["result"]                            # submitted twice (double click, auto-submit): same result
            p, sid = exam["paper"], exam["sid"]
            took = time.time() - exam["started"]
            q1, a1 = mark_scheduling(p["scheduling"], answers.get("q1") or {})
            q2, a2 = mark_bankers(p["bankers"], answers.get("q2") or {})
            q3, a3 = mark_semaphore(p["semaphore"], answers.get("q3") or {})
            q4 = mark_detection(p["detection"], answers.get("q4") or {})
            q5 = mark_mcq(p["mcq"], answers.get("q5") or [])
            changes: dict = {}
            for k, (pd, a) in enumerate(((p["scheduling"], a1), (p["bankers"], a2), (p["semaphore"], a3)), start=1):
                changes.update(students.record_attempt(sid, pd, f"exam:{exam_id}:q{k}", a, 1, 0, False, took))
            total = sum(q["marks"] for q in (q1, q2, q3, q4, q5))
            exam["result"] = {
                "id": exam_id, "total": round(total, 1), "out_of": 30, "minutes_taken": round(took / 60, 1),
                "late": took > MINUTES * 60 + 30,
                "questions": [{"n": n, "title": t, **q} for n, t, q in
                              ((1, "CPU scheduling", q1), (2, "Banker's algorithm", q2), (3, "Semaphores", q3),
                               (4, "Deadlock detection", q4), (5, "Concepts", q5))],
                "mastery": [{"skill": SKILLS.get(k, k), "before": round(b, 3), "after": round(a_, 3)} for k, (b, a_) in changes.items()]}
            return exam["result"]
