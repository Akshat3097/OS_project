def gantt_until(gantt: list, t: int) -> list[tuple]:
    out = []
    for s in gantt:
        if s.start >= t:
            break
        out.append((s.pid, s.start, min(s.end, t)))
    return out


def _event_text(res: scheduling.ScheduleResult, d, prev_seg) -> str:
    """Plain-language description of what just happened at decision time d.time."""
    t = d.time
    arrivals = [p.pid for p in res.processes if p.arrival == t]
    parts = []
    if prev_seg is not None and prev_seg[0] != IDLE and prev_seg[2] == t:
        pid = prev_seg[0]
        if res.results[pid].completion == t:
            parts.append(f"{pid} has just finished")
        elif res.algorithm == "RR":
            parts.append(f"{pid}'s time quantum has ended")
    if prev_seg is not None and prev_seg[0] == IDLE and prev_seg[2] == t:
        parts.append("the CPU was idle")
    if arrivals:
        parts.append(f"{', '.join(arrivals)} {'arrives' if len(arrivals) == 1 else 'arrive'}")
    if d.kind in ("preempt", "no_preempt") and not arrivals:
        parts.append("a new process has arrived")
    running = None
    if d.kind in ("preempt", "no_preempt"):
        running = d.preempted if d.kind == "preempt" else d.chosen
        parts.append(f"{running} is running")
    if t == 0 and not parts:
        parts.append("the system starts")
    text = "; ".join(parts) if parts else "the CPU is free"
    return f"t = {t}: {text}."


def scheduling_steps(res: scheduling.ScheduleResult) -> list[dict]:
    """One step per decision (dispatch, preemption check), skipping idle periods."""
    steps = []
    segs = [(s.pid, s.start, s.end) for s in res.gantt]
    for d in res.decisions:
        if d.kind == "idle":
            continue
        prev = next((s for s in reversed(segs) if s[2] <= d.time), None)
        if d.kind == "no_preempt" or d.kind == "preempt":
            question = "Which process should have the CPU now?"
        else:
            question = "Which process runs next?"
        options = sorted({r["pid"] for r in d.ready}, key=lambda x: (len(x), x))
        steps.append({"time": d.time, "event": _event_text(res, d, prev), "question": question,
                      "options": options, "answer": d.chosen, "reason": d.reason, "ready": d.ready,
                      "kind": d.kind, "queue": [r["pid"] for r in d.ready] if res.algorithm == "RR" else None})
    return steps


def results_breakdown(res: scheduling.ScheduleResult) -> list[str]:
    lines = []
    for p in res.processes:
        r = res.results[p.pid]
        lines.append(f"**{p.pid}**: CT = {r.completion} · TAT = {r.completion} − {p.arrival} = {r.turnaround} · "
                     f"WT = {r.turnaround} − {p.burst} = {r.waiting}")
    return lines


