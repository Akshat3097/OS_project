def semaphore_steps(initial: dict, ops: list[dict]) -> list[dict]:
    tr = semaphore.trace(initial, ops)
    out = []
    for s in tr["steps"]:
        before, after = s["value_before"], s["value_after"]
        if s["op"] == "wait":
            outcome = "blocks" if after < 0 else "continues"
            outcomes = ["continues", "blocks"]
        else:
            outcome = f"wakes {s['woken']}" if s["woken"] else "nobody is woken"
            waiting = [q for q in (out[-1]["queue"] if out else [])] if out else []
            wake_opt = f"wakes {s['woken']}" if s["woken"] else (f"wakes {waiting[0]}" if waiting else "wakes a waiting process")
            outcomes = ["nobody is woken", wake_opt]
        out.append({"step": s["step"], "pid": s["pid"], "op": s["op"], "sem": s["sem"], "before": before, "after": after,
                    "value_options": sorted({before - 1, before, before + 1}), "outcome": outcome, "outcomes": outcomes,
                    "effect": s["effect"], "queue": list(s["queues"][s["sem"]])})
    return out
