"""
"Explain it back" (teach-back): the student explains the topic in their own words for about a
minute (spoken, converted to text), the tutor works out which key ideas they understood, asks ONE
question aimed at the weakest idea, then gives pointers.

Assessment uses two judges:
  * an LLM judge (Ollama, JSON output) that understands paraphrase, when the model is running;
  * a keyword rubric that always runs and works offline (speech-to-text friendly).
The question is generated by the OS Engine (or taken from the lesson's question pool), so its
answer is always verified.
"""
from __future__ import annotations

import json
import random
import re

from engine import bankers, generator, semaphore
from tutor import lessons as L

RATING_ORDER = {"missing": 0, "partial": 1, "clear": 2}


def normalise(text: str) -> str:
    t = text.lower().replace("-", " ").replace("’", "'")
    t = re.sub(r"[^a-z0-9'+=<>≤ ]+", " ", t)
    t = re.sub(r"\bpre ?(amp|empt)", "preempt", t)          # speech-to-text: "preamps", "pre-empt" → preempt
    # abbreviations spoken letter by letter: "s r t f" → "srtf", "f c f s" → "fcfs"
    t = re.sub(r"\b[a-z](?: [a-z]\b){2,3}", lambda m: m.group(0).replace(" ", ""), t)
    return re.sub(r"\s+", " ", t).strip()


# ============================================================================ assessment
def _has(t: str, alt: str) -> bool:
    # short words ("ct", "up", "add") must match as whole words, longer ones as substrings ("preempt" → "preempted")
    return re.search(rf"\b{re.escape(alt)}\b", t) is not None if len(alt) <= 3 else alt in t


def keyword_assess(lesson: dict, transcript: str) -> dict:
    t = normalise(transcript)
    ideas, hit_counts = {}, {}
    for idea in lesson["ideas"]:
        groups = idea["groups"]
        hits = sum(any(_has(t, alt) for alt in g) for g in groups)
        ratio = hits / len(groups)
        ideas[idea["id"]] = "clear" if ratio == 1 else "partial" if ratio >= 0.5 else "missing"
        hit_counts[idea["id"]] = hits
    mis = [m["id"] for m in lesson["misconceptions"] if m.get("pattern") and re.search(m["pattern"], t)]
    return _apply_misconceptions(lesson, {"ideas": ideas, "misconceptions": mis, "source": "keyword rubric",
                                          "hits": hit_counts})


def real_words(transcript: str) -> tuple[int, int]:
    """(words of two or more letters, how many of them are different): "f f f f" is not an explanation."""
    words = re.findall(r"[a-z]{2,}", transcript.lower())
    return len(words), len(set(words))


def enough_to_assess(transcript: str) -> bool:
    n, distinct = real_words(transcript)
    return n >= 15 and distinct >= 8


def _apply_misconceptions(lesson: dict, a: dict) -> dict:
    """A stated misconception means the idea it contradicts is not understood, whatever keywords matched."""
    for m in lesson["misconceptions"]:
        if m["id"] in a["misconceptions"] and m.get("idea") in a["ideas"]:
            a["ideas"][m["idea"]] = "missing"
    return a


def _mis_ideas(lesson: dict, a: dict) -> set:
    return {m.get("idea") for m in lesson["misconceptions"] if m["id"] in a.get("misconceptions", [])}


JUDGE_SYSTEM = (
    "You assess a university student's spoken explanation of an Operating Systems topic. The text came from "
    "speech-to-text, so ignore filler words and transcription errors and accept paraphrases. For EACH key idea, "
    "decide: \"clear\" (stated correctly), \"partial\" (mentioned but vague or incomplete), or \"missing\". "
    "List a misconception id ONLY if the student clearly states that wrong belief. Reply with JSON only."
)

# The stricter judge: every credited idea must come with the student's own words as evidence, and the code checks
# that the quote really is in the explanation (an 8B model asked only for ratings tends to say "clear" to please).
EVIDENCE_SYSTEM = (
    "You are a strict examiner checking a student's explanation of an Operating Systems topic. The text came from "
    "speech-to-text: ignore filler words and small transcription errors, and accept the student's own words.\n"
    "For EACH key idea decide what the STUDENT actually said:\n"
    "- clear: the student states the idea correctly.\n"
    "- partial: the student states part of it, or says it vaguely, and nothing about it is wrong.\n"
    "- missing: not said, only hinted at, or said wrongly.\n"
    "For every idea you rate clear or partial, copy into \"evidence\" the student's exact words that show it (a short "
    "quote, word for word from the explanation). If you cannot quote the student, the rating is missing.\n"
    "A list of technical terms with no explanation is NOT an explanation: rate every idea missing. Talk about another "
    "subject is NOT an explanation either.\n"
    "Only if the student clearly SAYS one of the listed wrong beliefs, add it to \"misconceptions\" with the student's "
    "exact words that say it as evidence, and rate that idea missing. Never list a wrong belief the student did not say.\n"
    "Reply with JSON only."
)
_SHOT_IDEAS = ("- frames: Memory is split into fixed-size frames and a process into pages of the same size.\n"
               "- page_table: A page table maps each page to the frame that holds it.")
_SHOT_MIS = "- no_fragmentation: Paging removes all fragmentation (it still has internal fragmentation)"
EVIDENCE_SHOTS = [
    ("Paging", "uh so paging divides the process into pages and memory into frames which are the same size. and it "
               "means there is no fragmentation at all",
     {"ideas": {"frames": {"rating": "clear",
                           "evidence": "divides the process into pages and memory into frames which are the same size"},
                "page_table": {"rating": "missing", "evidence": ""}},
      "misconceptions": [{"id": "no_fragmentation", "evidence": "there is no fragmentation at all"}],
      "did_well": "You described pages and frames correctly.",
      "most_important_gap": "Say how a page is found: the page table maps pages to frames."}),
    ("Paging", "page frame page table TLB fragmentation memory size",
     {"ideas": {"frames": {"rating": "missing", "evidence": ""}, "page_table": {"rating": "missing", "evidence": ""}},
      "misconceptions": [], "did_well": "",
      "most_important_gap": "Explain in sentences what paging does, not only the terms."}),
]
FUNCTION_WORDS = set("is are was be the a an of to it its when if and or so by that which from in on as then means "
                     "minus than each every one can not no only until till before after goes runs waits keeps has have "
                     "gets takes there they their this these with for at into while because".split())


def _tokens(text: str) -> list[str]:
    return re.findall(r"[a-z0-9]+", normalise(text))


def quote_ok(quote: str, transcript: str) -> bool:
    """Is this really the student's words, and an actual statement (not a bare list of terms)?"""
    q, said = _tokens(quote), set(_tokens(transcript))
    if len(q) < 3:
        return False
    found = sum(t in said for t in q) / len(q)
    return found >= 0.8 and any(t in FUNCTION_WORDS for t in q)


def _judge_messages(lesson: dict, transcript: str, evidence: bool) -> list[dict]:
    if evidence:
        shape = ('{"ideas": {"<idea id>": {"rating": "clear|partial|missing", "evidence": "<quote or empty>"}, ...}, '
                 '"misconceptions": [{"id": "<wrong belief id>", "evidence": "<quote>"}], '
                 '"did_well": "one short sentence", "most_important_gap": "one short sentence"}')
    else:
        shape = ('{"ideas": {"<idea id>": "clear|partial|missing", ...}, "misconceptions": [], '
                 '"did_well": "one short sentence", "most_important_gap": "one short sentence"}')

    def user(title, ideas, mis, text):
        return (f"TOPIC: {title}\nKEY IDEAS:\n{ideas}\nWRONG BELIEFS TO LISTEN FOR:\n{mis}\n\n"
                f"STUDENT'S EXPLANATION:\n\"\"\"{text.strip()}\"\"\"\n\nReturn JSON in this shape:\n{shape}")
    ideas = "\n".join(f"- {i['id']}: {i['statement']}" for i in lesson["ideas"])
    mis = "\n".join(f"- {m['id']}: {m['text']}" for m in lesson["misconceptions"]) or "(none)"
    msgs = [{"role": "system", "content": EVIDENCE_SYSTEM if evidence else JUDGE_SYSTEM}]
    if evidence:
        for title, text, answer in EVIDENCE_SHOTS:
            msgs += [{"role": "user", "content": user(title, _SHOT_IDEAS, _SHOT_MIS, text)},
                     {"role": "assistant", "content": json.dumps(answer)}]
    msgs.append({"role": "user", "content": user(lesson["title"], ideas, mis, transcript)})
    return msgs


def llm_assess(client, lesson: dict, transcript: str, evidence: bool = True) -> dict | None:
    try:
        import requests
        if hasattr(client, "make_room"):
            client.make_room()                         # the judge model takes the GPU from the tutor model
        r = requests.post(f"{client.url}/api/chat", timeout=120, json={
            "model": client.model, "stream": False, "format": "json", "keep_alive": "30m",
            # capped against loops, but no repeat penalty: JSON repeats its keys by design
            "options": {"temperature": 0, "seed": 7, "num_ctx": 4096, "num_predict": 900},
            "messages": _judge_messages(lesson, transcript, evidence)})
        r.raise_for_status()
        data = json.loads(r.json()["message"]["content"])
    except Exception:
        return None
    if not isinstance(data, dict) or not isinstance(data.get("ideas"), dict):
        return None                                    # an unreadable reply: the keyword rubric is used instead
    valid_ids = {i["id"] for i in lesson["ideas"]}
    out, quotes, rejected = {}, {}, []
    for k, v in data["ideas"].items():
        if k not in valid_ids:
            continue
        rating = str((v.get("rating") if isinstance(v, dict) else v) or "").lower()
        if rating not in RATING_ORDER:
            continue
        if evidence and rating != "missing":
            quote = str(v.get("evidence") or "") if isinstance(v, dict) else ""
            if quote_ok(quote, transcript):
                quotes[k] = quote[:200]
            else:
                rejected.append(k)                     # credited without the student's own words: not credited
                rating = "missing"
        out[k] = rating
    if len(out) < len(valid_ids):
        return None
    mis_ids = {m["id"] for m in lesson["misconceptions"]}
    said = data.get("misconceptions") or []
    said = said if isinstance(said, list) else [said]
    if evidence:
        # A wrong belief counts only with the student's own words, like a credited idea, and only if (1) those words
        # are about the topic (one of the idea's keyword groups appears: "the top two teams go to the final" is not a
        # Round Robin misconception) and (2) the judge did not itself credit that idea (it quoted the same correct
        # sentence as evidence for both in the evaluation).
        idea_of = {m["id"]: m.get("idea") for m in lesson["misconceptions"]}
        groups = {i["id"]: i["groups"] for i in lesson["ideas"]}
        kept = []
        for m in said:
            if not isinstance(m, dict) or m.get("id") not in idea_of:
                continue
            quote, idea = str(m.get("evidence") or ""), idea_of[m["id"]]
            on_topic = any(_has(normalise(quote), alt) for g in groups.get(idea, []) for alt in g)
            if quote_ok(quote, transcript) and on_topic and out.get(idea, "missing") == "missing":
                kept.append(m["id"])
        said = kept
    else:
        said = [m.get("id") if isinstance(m, dict) else m for m in said]
    return _apply_misconceptions(lesson, {
        "ideas": out, "evidence": quotes, "rejected": rejected,
        "misconceptions": [m for m in said if isinstance(m, str) and m in mis_ids],
        "did_well": str(data.get("did_well") or "")[:300], "gap": str(data.get("most_important_gap") or "")[:300],
        "source": f"LLM judge ({client.model})" + (", evidence-checked" if evidence else "")})


def combine(kw: dict, result: dict | None, cap: bool = True) -> dict:
    """The final assessment: the LLM's when there is one, else the keyword rubric's. With cap, the LLM may credit a
    paraphrase but not an idea where none of its keyword groups appear (an LLM rated "f f f f …" 4 of 5 clear)."""
    if result is None:
        return {**kw, "ideas": dict(kw["ideas"])}
    result = {**result, "ideas": dict(result["ideas"])}
    if cap:
        capped = [k for k, v in result["ideas"].items() if v != "missing" and kw["hits"].get(k, 0) == 0]
        for k in capped:
            result["ideas"][k] = "missing"
        if capped:
            result["source"] += " + keyword check"
    if not any(v == "clear" for v in result["ideas"].values()):
        result["did_well"] = ""
    return result


def judge_client(client):
    """The model that judges explanations: config.JUDGE_MODEL when it is installed, else the chat model."""
    if client is None:
        return None
    import config
    from tutor.llm import OllamaClient
    installed = client.list_models() if hasattr(client, "list_models") else []
    match = next((m for m in installed if m.split(":")[0] == config.JUDGE_MODEL.split(":")[0]), None)
    return OllamaClient(url=client.url, model=match) if match else client


def assess(lesson: dict, transcript: str, client=None, evidence: bool = True, cap: bool = True) -> dict:
    kw = keyword_assess(lesson, transcript)
    client = judge_client(client)
    raw = llm_assess(client, lesson, transcript, evidence) if client is not None and client.available() else None
    result = combine(kw, raw, cap)
    result["keyword"] = kw
    result["words"] = len(transcript.split())
    mi = _mis_ideas(lesson, result)
    order = sorted(lesson["ideas"], key=lambda i: (RATING_ORDER[result["ideas"][i["id"]]], i["id"] not in mi))
    result["target"] = order[0]["id"] if RATING_ORDER[result["ideas"][order[0]["id"]]] < 2 else None
    result["score"] = sum(RATING_ORDER[v] for v in result["ideas"].values()) / (2 * len(lesson["ideas"]))
    return result


def target_idea(lesson: dict, assessment: dict, already_asked: list[str]) -> tuple[dict, str]:
    """Pick the idea to question: a misconception's idea first, then the weakest idea not yet asked."""
    ideas = [i for i in lesson["ideas"] if i["id"] not in already_asked] or lesson["ideas"]
    mi = _mis_ideas(lesson, assessment)
    ranked = sorted(ideas, key=lambda i: (RATING_ORDER[assessment["ideas"][i["id"]]], i["id"] not in mi,
                                          lesson["ideas"].index(i)))
    best = ranked[0]
    if RATING_ORDER[assessment["ideas"][best["id"]]] == 2:
        return best, "challenge"
    return best, "gap"


# ============================================================================ questions
def make_question(lesson: dict, idea: dict, seed: int | None = None) -> dict:
    spec = idea["question"]
    rng = random.Random(seed if seed is not None else random.randrange(10**9))
    if spec["type"] == "mcq":
        q = lesson["mcq"][spec["index"]]
        opts = list(q["options"])
        rng.shuffle(opts)
        return {"kind": "mcq", "idea": idea["id"], "q": q["q"], "options": opts}
    if spec["type"] in ("decision", "metric"):
        for _ in range(300):
            s = rng.randrange(10**9)
            prob = generator.generate_scheduling(spec["algorithm"], spec.get("difficulty", 2), s)
            res = prob.solve()
            if spec["type"] == "decision":
                steps = L.scheduling_steps(res)
                ev = spec["event"]
                for k, st in enumerate(steps):
                    if len(st["options"]) < 2:
                        continue
                    ok = (ev == st["kind"]) or (ev == "dispatch" and st["kind"] == "dispatch")
                    if ev == "dispatch_after_preempt":
                        ok = st["kind"] == "dispatch" and any(r["remaining"] < r["burst"] for r in st["ready"])
                    if ok:
                        return {"kind": "decision", "idea": idea["id"], "problem": prob.to_dict(), "step": k}
            else:
                pieces = {}
                for seg in res.gantt:
                    if seg.pid != "IDLE":
                        pieces[seg.pid] = pieces.get(seg.pid, 0) + 1
                cands = [p for p in prob.processes if (pieces[p.pid] > 1 if spec.get("multi_piece") else p.arrival > 0)]
                if cands:
                    p = rng.choice(cands)
                    return {"kind": "metric", "idea": idea["id"], "problem": prob.to_dict(), "pid": p.pid,
                            "field": spec["field"]}
        raise RuntimeError("could not generate a matching question")
    if spec["type"] == "semaphore":
        for _ in range(300):
            prob = generator.generate_semaphore(2, rng.randrange(10**9))
            steps = L.semaphore_steps(prob.initial, prob.ops)
            for k, st in enumerate(steps):
                if (spec["want"] == "block" and st["outcome"] == "blocks") or \
                        (spec["want"] == "wake" and st["outcome"].startswith("wakes")):
                    return {"kind": "semaphore", "idea": idea["id"], "problem": prob.to_dict(), "step": k}
        raise RuntimeError("could not generate a semaphore question")
    if spec["type"] == "bankers":
        prob = generator.generate_bankers(2, rng.randrange(10**9))
        return {"kind": "bankers", "idea": idea["id"], "problem": prob.to_dict()}
    raise ValueError(spec["type"])


def bankers_valid_first(prob) -> list[str]:
    need = bankers.compute_need(prob.maximum, prob.allocation)
    return [f"P{i}" for i, n in enumerate(need) if all(a <= b for a, b in zip(n, prob.available))]


def check_answer(q: dict, answer) -> dict:
    """Returns {"ok": bool, "explanation": str, "correct": str}."""
    if q["kind"] == "mcq":
        text, ok, why = next(o for o in q["options"] if o[0] == answer)
        right = next(o[0] for o in q["options"] if o[1])
        return {"ok": ok, "explanation": why, "correct": right}
    prob = generator.problem_from_dict(q["problem"])
    if q["kind"] == "decision":
        st = L.scheduling_steps(prob.solve())[q["step"]]
        return {"ok": answer == st["answer"], "explanation": st["reason"], "correct": st["answer"]}
    if q["kind"] == "metric":
        r = prob.solve().results[q["pid"]]
        p = next(x for x in prob.processes if x.pid == q["pid"])
        val = {"CT": r.completion, "TAT": r.turnaround, "WT": r.waiting}[q["field"]]
        how = {"CT": f"CT = end of {q['pid']}'s last block = {r.completion}",
               "TAT": f"TAT = CT − AT = {r.completion} − {p.arrival} = {r.turnaround}",
               "WT": f"WT = CT − AT − BT = {r.completion} − {p.arrival} − {p.burst} = {r.waiting}"}[q["field"]]
        try:
            ok = answer is not None and int(answer) == val
        except (TypeError, ValueError):
            ok = False
        return {"ok": ok, "explanation": how, "correct": str(val)}
    if q["kind"] == "semaphore":
        st = L.semaphore_steps(prob.initial, prob.ops)[q["step"]]
        v, o = answer
        sign = "−" if st["op"] == "wait" else "+"
        return {"ok": v == st["after"] and o == st["outcome"],
                "explanation": f"{st['sem']} = {st['before']} {sign} 1 = {st['after']}, so {st['pid']} {st['outcome']}.",
                "correct": f"{st['after']}, {st['outcome']}"}
    # bankers: which process can finish first?
    valid = bankers_valid_first(prob)
    need = bankers.compute_need(prob.maximum, prob.allocation)
    k = int(answer[1:])
    why = (f"{answer}: Need {need[k]} vs Available {prob.available}. "
           + ("Need ≤ Available for every resource, so it can finish." if answer in valid else
              "Some resource is short, so it cannot finish yet."))
    return {"ok": answer in valid, "explanation": why + f" Valid first choices: {', '.join(valid) or 'none (unsafe)'}.",
            "correct": ", ".join(valid)}


# ============================================================================ pointers
def pointers(lesson: dict, assessment: dict, results: list[dict]) -> dict:
    by_id = {i["id"]: i for i in lesson["ideas"]}
    clear = [by_id[k]["statement"] for k, v in assessment["ideas"].items() if v == "clear"]
    partial = [by_id[k]["statement"] for k, v in assessment["ideas"].items() if v == "partial"]
    missing = [by_id[k]["statement"] for k, v in assessment["ideas"].items() if v == "missing"]
    mis = [m["text"] for m in lesson["misconceptions"] if m["id"] in assessment.get("misconceptions", [])]
    wrong_q = [r for r in results if not r["ok"]]
    if assessment["score"] >= 0.8 and not wrong_q and not mis:
        verdict, next_step = "Strong understanding", "practice"
    elif assessment["score"] >= 0.5 and len(wrong_q) <= 1:
        verdict, next_step = "Good start, a few gaps", "guided"
    else:
        verdict, next_step = "Needs another look", "rewatch"
    return {"verdict": verdict, "clear": clear, "partial": partial, "missing": missing, "misconceptions": mis,
            "questions": results, "next": next_step}
